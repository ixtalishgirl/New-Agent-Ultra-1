#!/usr/bin/env python3
"""Regenerate agent/configs/AGENT_SYSTEM_PROMPT.md from the live registry.

Run from the repo root:  python3 agent/configs/gen_system_prompt.py
Keeps the rendered prompt in sync with build_full_registry() and the
Permission Manager. Never hand-edit AGENT_SYSTEM_PROMPT.md — edit the
registry/permissions and re-run this script.
"""
from __future__ import annotations
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO_ROOT))

from agent.model.prompt_builder import build_system_prompt  # noqa: E402
from agent.tools.registry import build_full_registry  # noqa: E402
from agent.tools.permission_manager import build_manager  # noqa: E402


def main() -> None:
    prompt = build_system_prompt()
    reg = build_full_registry()
    pm = build_manager(reg)
    enabled, total = pm.count_enabled()
    out = (
        "# AGENT SYSTEM PROMPT (rendered)\n\n"
        f"_Auto-generated by `agent/configs/gen_system_prompt.py`. "
        f"Do not hand-edit — re-run the script._\n\n"
        f"- Tools: {len(reg.discover())}\n"
        f"- Permissions: {enabled}/{total} enabled "
        f"({total - enabled} locked denials)\n\n"
        "---\n\n" + prompt + "\n"
    )
    dest = REPO_ROOT / "agent" / "configs" / "AGENT_SYSTEM_PROMPT.md"
    dest.write_text(out, encoding="utf-8")
    print(f"wrote {dest} ({len(out)} chars)")


if __name__ == "__main__":
    main()
